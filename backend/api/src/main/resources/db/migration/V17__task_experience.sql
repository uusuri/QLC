CREATE TABLE user_task_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    task_id BIGINT NOT NULL,
    xp INTEGER NOT NULL CHECK (xp IN (10, 20, 30)),
    submission_id UUID NOT NULL,
    awarded_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_user_task_experience UNIQUE (user_id, task_id)
);

-- Preserve earned XP if a task/submission is removed or its difficulty changes later.
-- Legacy attempts excluded from learning progress and demo attempts are not eligible.
INSERT INTO user_task_experience (user_id, task_id, xp, submission_id, awarded_at)
SELECT DISTINCT ON (s.user_id, s.task_id)
    s.user_id, s.task_id, 10 * LEAST(3, GREATEST(1, t.difficulty)), s.id, s.created_at
FROM submissions s
JOIN tasks t ON t.id = s.task_id
WHERE s.user_id IS NOT NULL
  AND s.status = 'FINISHED'
  AND s.verdict = 'AC'
  AND s.counts_for_progress = TRUE
ORDER BY s.user_id, s.task_id, s.created_at, s.id;
