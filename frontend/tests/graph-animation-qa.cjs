// Run against a local Next server. API calls are intercepted; no real courses are changed.
const assert = require("node:assert/strict");
const path = require("node:path");
const fs = require("node:fs");
const { chromium } = require(process.env.QLC_PLAYWRIGHT_MODULE || "playwright");
const load = require("./load-ts.cjs");
const { findGraphBlocks, parseGraphAnimation } = load(path.join(__dirname, "../services/graphAnimation.ts"));
const base = process.env.QLC_QA_URL || "http://127.0.0.1:3000";
const out = process.env.QLC_QA_OUTPUT || path.join(require("node:os").tmpdir(), "qlc-graph-qa");
const course = { id: 2, name: "Графы QA", description: "", price: 0, priceInStars: 0, multilingual: false, availableLanguages: ["JAVA21", "CPP23"] };
const moduleItem = { id: 201, courseId: 2, name: "Алгоритмы QA", description: "", position: 1 };
let lesson = { id: 301, moduleId: 201, name: "Анимации QA", description: "", position: 1, published: true,
  contentMd: "# Теория\n\nТекст до анимации.\n\nТекст после анимации.", contentByLanguage: { JAVA21: "Java theory", CPP23: "C++ theory" } };
let saves = 0;

(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.QLC_CHROMIUM_PATH ? { executablePath: process.env.QLC_CHROMIUM_PATH } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    await context.addInitScript(() => localStorage.setItem("qlc:auth-token", "graph-test-only"));
    await context.route("**/api/**", async route => {
      const url = new URL(route.request().url()).pathname;
      let body;
      if (url === "/api/auth/me") body = { id: 999, username: "graph_tester", email: "qa@example.invalid", role: "ROLE_ADMIN" };
      else if (url === "/api/courses") body = [course];
      else if (url === "/api/courses/2") body = course;
      else if (url === "/api/courses/2/modules") body = [moduleItem];
      else if (url === "/api/modules/201") body = moduleItem;
      else if (url === "/api/modules/201/lessons") body = [lesson];
      else if (url === "/api/admin/lessons/301") body = lesson;
      else if (url === "/api/lessons/301" && route.request().method() === "PUT") {
        lesson = { ...lesson, ...route.request().postDataJSON() }; saves++; body = lesson;
      } else if (url === "/api/lessons/301/learn") body = { course, module: moduleItem, lesson, tasks: [], acceptedTaskIds: [], access: true };
      else if (url === "/api/lessons/301/tasks" || url === "/api/lessons/301/task-outline" || url === "/api/users/me/learning-courses") body = [];
      else if (url === "/api/cart") body = { courseIds: [] };
      else return route.fulfill({ status: 404, json: { message: `No fixture: ${url}` } });
      return route.fulfill({ status: 200, json: body });
    });
    const page = await context.newPage();
    page.on("pageerror", error => errors.push(error.message));
    page.on("dialog", dialog => dialog.accept());
    await page.goto(base + "/admin/content");
    await page.getByRole("navigation", { name: "Структура курса", exact: true }).getByRole("combobox").selectOption("2");
    await page.getByRole("button", { name: "Развернуть: Алгоритмы QA" }).click();
    await page.getByRole("button", { name: "Урок Анимации QA", exact: true }).click();
    const theory = page.getByRole("region", { name: "Редактор теории", exact: true });
    const markdown = theory.locator("textarea");
    await markdown.fill(lesson.contentMd);
    await markdown.evaluate(input => input.setSelectionRange(input.value.indexOf("Текст после"), input.value.indexOf("Текст после")));
    await theory.getByRole("button", { name: "Анимация", exact: true }).click();
    const editor = page.getByRole("region", { name: "Редактор анимации", exact: true });
    await editor.getByLabel("Шаблон анимации").selectOption("reverse");
    await editor.getByRole("button", { name: "Заменить шаблоном" }).click();
    await editor.getByLabel("Название", { exact: true }).fill("Разворот списка QA");
    assert(await page.getByRole("button", { name: "Сохранить урок и все версии", exact: true }).isDisabled());
    await editor.getByLabel("Название", { exact: true }).press("Enter");
    assert.equal(saves, 0, "Enter inside the animation editor must not save stale theory");
    // Drag a vertex and verify that its coordinates survive save/reopen.
    const vertex = editor.getByRole("button", { name: "Вершина A", exact: true });
    await vertex.scrollIntoViewIfNeeded();
    const box = await vertex.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 25, box.y + box.height / 2 + 20, { steps: 5 }); await page.mouse.up();
    const movedX = Number(await editor.getByLabel("X", { exact: true }).inputValue());
    assert(movedX > 140);
    await editor.getByLabel("Редактируемый шаг").selectOption("4");
    await editor.getByRole("button", { name: "Добавить шаг-копию" }).click();
    await editor.getByLabel("Описание шага").fill("Контрольный шаг QA");
    await editor.getByLabel("Трассировка A → B").selectOption("B-A:B");
    await editor.getByRole("button", { name: "Вставить в теорию" }).click();
    await theory.getByRole("button", { name: "Изменить анимацию 1" }).waitFor();
    const firstSave = page.waitForResponse(response => response.url().endsWith("/api/lessons/301") && response.request().method() === "PUT");
    await page.getByRole("button", { name: "Сохранить урок и все версии", exact: true }).click(); await firstSave;
    assert.equal(saves, 1);
    assert.match(lesson.contentMd, /Текст до анимации/); assert.match(lesson.contentMd, /Текст после анимации/);
    assert.equal(lesson.contentByLanguage.JAVA21, "Java theory");
    let animation = parseGraphAnimation(findGraphBlocks(lesson.contentMd)[0].source);
    assert.equal(animation.steps.length, 6); assert.equal(animation.nodes[0].x, movedX);
    await theory.getByRole("button", { name: "Изменить анимацию 1" }).click();
    assert.equal(await editor.getByLabel("Название", { exact: true }).inputValue(), "Разворот списка QA");
    await editor.getByRole("button", { name: "Отмена", exact: true }).click();
    await page.reload();
    await page.getByRole("button", { name: "Изменить анимацию 1" }).waitFor();
    await page.goto(base + "/lessons/301");
    const player = page.getByRole("region", { name: "Анимация: Разворот списка QA", exact: true });
    await player.waitFor();
    await player.getByRole("button", { name: "Вперёд", exact: true }).click();
    await player.locator("[data-graph-tracer]").waitFor();
    const start = await player.locator("[data-graph-tracer]").getAttribute("cx");
    await page.waitForTimeout(350);
    assert.notEqual(await player.locator("[data-graph-tracer]").getAttribute("cx"), start);
    await player.getByRole("slider", { name: "Шаг анимации" }).fill("5");
    await player.getByText("Контрольный шаг QA", { exact: true }).waitFor();
    await player.getByRole("button", { name: "Назад", exact: true }).click();
    await player.getByText("C.next = B. curr = null: цикл завершён, новая голова — C.").waitFor();
    await player.getByRole("button", { name: "В начало", exact: true }).click();
    await player.getByLabel("Скорость анимации").selectOption("800");
    await player.getByRole("button", { name: "Воспроизвести", exact: true }).click();
    await page.waitForTimeout(950);
    await player.getByRole("button", { name: "Пауза", exact: true }).click();
    const paused = await player.getByRole("slider").inputValue();
    const pausedMarker = await player.locator("[data-graph-tracer]").getAttribute("cx");
    await page.waitForTimeout(1000);
    assert.equal(await player.getByRole("slider").inputValue(), paused);
    assert.equal(await player.locator("[data-graph-tracer]").getAttribute("cx"), pausedMarker);
    await page.screenshot({ path: path.join(out, "lesson-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(out, "lesson-mobile.png"), fullPage: true });
    // Different language versions use the same editor without replacing each other.
    course.multilingual = true;
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base + "/admin/content");
    await theory.getByRole("group", { name: "Язык теории" }).getByRole("button", { name: /Java/ }).click();
    await theory.getByRole("button", { name: "Анимация", exact: true }).click();
    await editor.getByRole("button", { name: "Добавить вершину", exact: true }).click();
    await editor.getByLabel("Подпись вершины").fill("C");
    await editor.getByLabel("Откуда", { exact: true }).selectOption("B");
    await editor.getByLabel("Куда", { exact: true }).selectOption("n1");
    await editor.getByLabel("Со стрелкой", { exact: true }).uncheck();
    await editor.getByRole("button", { name: "Добавить связь", exact: true }).click();
    await editor.getByLabel("Трассировка A → B").selectOption("e1:n1");
    await editor.getByLabel("Пройдена связь e1").check();
    await editor.getByRole("button", { name: "Добавить указатель", exact: true }).click();
    await editor.getByRole("button", { name: "Вставить в теорию" }).click();
    const saved = page.waitForResponse(response => response.url().endsWith("/api/lessons/301") && response.request().method() === "PUT");
    await page.getByRole("button", { name: "Сохранить урок и все версии", exact: true }).click(); await saved;
    assert.equal(findGraphBlocks(lesson.contentByLanguage.JAVA21).length, 1);
    const custom = parseGraphAnimation(findGraphBlocks(lesson.contentByLanguage.JAVA21)[0].source);
    assert.equal(custom.nodes.length, 3);
    assert.deepEqual(custom.steps[0].trace, { edge: "e1", from: "n1", to: "B" });
    assert.deepEqual(custom.steps[0].pointers, [{ label: "current", node: "n1" }]);
    assert.equal(lesson.contentByLanguage.CPP23, "C++ theory");
    assert.equal(parseGraphAnimation(findGraphBlocks(lesson.contentMd)[0].source).title, animation.title);
    await theory.getByRole("button", { name: "Изменить анимацию 1" }).click();
    await editor.screenshot({ path: path.join(out, "editor-desktop.png") });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await editor.screenshot({ path: path.join(out, "editor-mobile.png") });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: "PASS", saves, errors, out }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
