def source_keys(i):
    if i==17:return ['segment','lazy','itmo']
    if i==18:return ['treap','implicit','itmo']
    if i in (10,11,12,13,14,20,22):return ['itmo-graphs','mit' if i<16 else 'mit-advanced']
    return ['itmo','mit' if i<16 else 'mit-advanced']

